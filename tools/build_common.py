import json
import os
from pathlib import Path
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
SDK_INCLUDE = ROOT / "sdk" / "include"  # fh2_plugin.h (v1, as upstream), forza_plugin.h (v2), forza_profile.h, ...
GAME_FOLDER = Path.home() / "FH2"  # default for the offline tests' game files


def find_zig(given):
    """Zig 0.15.2: `given`, else the ZIG environment variable, else zig on PATH."""
    for candidate in (given, os.environ.get("ZIG"), shutil.which("zig")):
        if candidate and Path(candidate).is_file():
            return Path(candidate).resolve()
    sys.exit("zig not found: pass --zig <zig.exe> (Zig 0.15.2) or set ZIG")


def show(command):
    """Prints a command with its path arguments shortened to their file names."""
    print(" ".join(Path(str(part)).name if os.sep in str(part) or "/" in str(part) else str(part)
                   for part in command), flush=True)


def run(command):
    show(command)
    subprocess.run([str(part) for part in command], check=True)


def write_if_changed(path, text):
    """Writes a generated file only when its text changes (keeps rebuilds incremental)."""
    path = Path(path)
    if not path.is_file() or path.read_text(encoding="utf-8") != text:
        path.write_text(text, encoding="utf-8", newline="\n")


def read_json(path):
    return json.loads(Path(path).read_text(encoding="utf-8"))


def version_rc(path, version, dll_name, description, product):
    """A VERSIONINFO resource script for a DLL."""
    numbers = (version.split(".") + ["0"] * 4)[:4]
    rc = f"""// Generated by build.py. Do not edit.
1 VERSIONINFO
FILEVERSION {",".join(numbers)}
PRODUCTVERSION {",".join(numbers)}
FILEOS 0x40004
FILETYPE 0x2
BEGIN
  BLOCK "StringFileInfo"
  BEGIN
    BLOCK "040904b0"
    BEGIN
      VALUE "FileDescription", "{description}"
      VALUE "FileVersion", "{version}"
      VALUE "InternalName", "{Path(dll_name).stem}"
      VALUE "OriginalFilename", "{dll_name}"
      VALUE "ProductName", "{product}"
      VALUE "ProductVersion", "{version}"
      VALUE "LegalCopyright", "Max (byzyn4ik), GPL-3.0-or-later"
    END
  END
  BLOCK "VarFileInfo"
  BEGIN
    VALUE "Translation", 0x409, 1200
  END
END
"""
    write_if_changed(path, rc)


def plugin_compiler(zig, *includes):
    """zig cc for a plugin DLL: C11, -Werror, no sanitizers, the SDK on the include path."""
    command = [zig, "cc", "-target", "x86_64-windows-gnu", "-std=c11", "-O2", "-Wall", "-Wextra", "-Werror",
               "-Wno-missing-field-initializers", "-fno-sanitize=all", "-DUNICODE", "-D_UNICODE",
               "-I", SDK_INCLUDE]
    for include in includes:
        command += ["-I", include]
    return command


def pe_identity(path):
    """(TimeDateStamp, SizeOfImage, [(virtual address, virtual size, raw offset, raw size)]) of a PE file."""
    import struct
    with open(path, "rb") as file:
        head = file.read(0x1000)
    pe = struct.unpack_from("<I", head, 0x3c)[0]
    if head[pe:pe + 4] != b"PE\0\0":
        raise ValueError(f"{path}: not a PE file")
    sections, optional_size = struct.unpack_from("<HxxxxxxxxxxxxH", head, pe + 6)
    timestamp = struct.unpack_from("<I", head, pe + 8)[0]
    image_size = struct.unpack_from("<I", head, pe + 24 + 56)[0]
    table = pe + 24 + optional_size
    found = []
    for index in range(sections):
        size, address, raw_size, raw = struct.unpack_from("<IIII", head, table + 40 * index + 8)
        found.append((address, size, raw, raw_size))
    return timestamp, image_size, found


def read_at_rva(path, sections, rva, length):
    """`length` bytes of a PE file at an RVA (None when the RVA is not backed by the file)."""
    for address, size, raw, raw_size in sections:
        if address <= rva and rva + length <= address + max(size, raw_size) and rva - address + length <= raw_size:
            with open(path, "rb") as file:
                file.seek(raw + rva - address)
                return file.read(length)
    return None


def pe_exports(path):
    """The names a PE file exports (from its export directory)."""
    import struct
    data = Path(path).read_bytes()
    pe = struct.unpack_from("<I", data, 0x3c)[0]
    sections, optional_size = struct.unpack_from("<H12xH", data, pe + 6)
    directory = struct.unpack_from("<I", data, pe + 24 + 112)[0]  # PE32+ DataDirectory[0]
    table = [struct.unpack_from("<IIII", data, pe + 24 + optional_size + 40 * i + 8) for i in range(sections)]

    def offset(rva):
        for size, address, raw_size, raw in table:
            if address <= rva < address + max(size, raw_size):
                return raw + rva - address
        raise ValueError(f"{path}: RVA {rva:#x} outside the sections")

    if not directory:
        return []
    base = offset(directory)
    count, names = struct.unpack_from("<I", data, base + 24)[0], offset(struct.unpack_from("<I", data, base + 32)[0])
    found = []
    for index in range(count):
        start = offset(struct.unpack_from("<I", data, names + 4 * index)[0])
        found.append(data[start:data.index(b"\0", start)].decode("ascii"))
    return found
